def main() -> int:
    Base.metadata.create_all(engine)
    случайно = random.Random(20260814)   # воспроизводимость: повторный прогон даёт то же
    пароли = []

    with SessionLocal() as session:
        уже_есть = session.scalar(select(func.count(Product.id))) or 0
        if уже_есть and not ПРИНУДИТЕЛЬНО:
            print(f"В базе уже {уже_есть} товаров. Для дозаполнения: --force")
            return 1

        # --- организация и склады ------------------------------------------
        организация = Organization(name="ООО «Розмарт Дистрибьюшн»", inn="300123456")
        session.add(организация)

        склады = {}
        for код, название in ФИЛИАЛЫ:
            склад = Warehouse(code=код, name=название)
            session.add(склад)
            склады[код] = склад

        виды_цен = {}
        for код, название, основной in ВИДЫ_ЦЕН:
            вид = PriceType(code=код, name=название, is_default=основной)
            session.add(вид)
            виды_цен[код] = вид

        session.flush()

        # --- каталог --------------------------------------------------------
        товары = []
        for порядок, (имя_категории, позиции) in enumerate(АССОРТИМЕНТ.items(), start=1):
            категория = ProductCategory(name=имя_категории, sort_order=порядок * 10)
            session.add(категория)
            session.flush()

            for номер, (имя, единица, кратность, упаковка, розница, ндс) in enumerate(позиции, 1):
                товар = Product(
                    category_id=категория.id,
                    code=f"{порядок:02d}-{номер:03d}",
                    name=имя,
                    unit=единица,
                    package_qty=Decimal(кратность),
                    package_name=упаковка,
                    barcode=f"478{случайно.randint(1000000000, 9999999999)}",
                    vat_rate=Decimal(ндс),
                )
                session.add(товар)
                session.flush()
                товары.append(товар)

                # Оптовая дешевле розницы на 12%, дилерская — на 18%.
                # Округление до сотни: ценники с точностью до сума в рознице
                # не встречаются.
                for код_вида, скидка in (("РОЗ", 0), ("ОПТ", 12), ("ДИЛ", 18)):
                    цена = (Decimal(розница) * (100 - скидка) / 100)
                    цена = (цена / 100).quantize(Decimal(1)) * 100
                    session.add(Price(
                        product_id=товар.id,
                        price_type_id=виды_цен[код_вида].id,
                        price=цена))

        # --- остатки по филиалам ---------------------------------------------
        # Центральный склад держит большой запас, филиалы — рабочий. Часть
        # позиций на филиалах намеренно в нуле: дефицит должен быть виден и
        # в кабинете, и агенту в каталоге.
        for товар in товары:
            for код, склад in склады.items():
                if код == "ЦС":
                    количество = случайно.randint(400, 2000)
                else:
                    количество = случайно.choice([0, 0, 15, 40, 60, 90, 120, 250])
                if количество == 0:
                    continue
                session.add(Stock(
                    product_id=товар.id, warehouse_id=склад.id,
                    qty=Decimal(количество)))
                session.add(StockMove(
                    product_id=товар.id, warehouse_id=склад.id,
                    qty=Decimal(количество), doc_type="manual",
                    comment="начальный остаток, демонстрационные данные"))

        # --- люди --------------------------------------------------------------
        for логин, фио, роль in ОФИС:
            пароль = random_password()
            session.add(User(
                login=логин, password_hash=hash_secret(пароль), full_name=фио,
                role=роль, must_change_password=True))
            пароли.append((логин, роль, пароль))

        агенты = {}
        for логин, фио, телефон, филиалы_агента in АГЕНТЫ:
            пароль = random_password()
            агент = User(
                login=логин, password_hash=hash_secret(пароль), full_name=фио,
                phone=телефон, role="agent", must_change_password=False)
            session.add(агент)
            session.flush()
            агенты[логин] = (агент, филиалы_агента)
            пароли.append((логин, "агент", пароль))

        # --- торговые точки -----------------------------------------------------
        точки_по_филиалам = {}
        for название, филиал, адрес, вид, отсрочка, лимит in ТОЧКИ:
            владелец = next(
                (а for а, ф in агенты.values() if филиал in ф), None)
            клиент = Customer(
                code=f"{филиал}-{len(точки_по_филиалам.get(филиал, [])) + 1:03d}",
                name=название,
                legal_name=f"ООО «{название.split('«')[-1].split('»')[0]}»"
                if "«" in название else название,
                inn=str(случайно.randint(300000000, 309999999)),
                phone=f"+998 7{случайно.randint(1, 9)} {случайно.randint(200, 999)}-"
                      f"{случайно.randint(10, 99)}-{случайно.randint(10, 99)}",
                address=адрес,
                price_type_id=виды_цен[вид].id,
                agent_id=владелец.id if владелец else None,
                payment_type="transfer" if отсрочка else "cash",
                credit_limit=Decimal(лимит),
                deferral_days=отсрочка,
            )
            session.add(клиент)
            session.flush()
            точки_по_филиалам.setdefault(филиал, []).append(клиент)

        # --- маршруты ------------------------------------------------------------
        # Каждый агент объезжает свои точки дважды в неделю: понедельник и
        # четверг — первый филиал, вторник и пятница — второй.
        for логин, (агент, филиалы_агента) in агенты.items():
            for номер, филиал in enumerate(филиалы_агента):
                for день in (номер + 1, номер + 4):
                    маршрут = Route(
                        agent_id=агент.id, weekday=день,
                        name=f"{филиал}, {'пн вт ср чт пт сб вс'.split()[день - 1]}")
                    session.add(маршрут)
                    session.flush()
                    for порядок, клиент in enumerate(точки_по_филиалам.get(филиал, []), 1):
                        session.add(RouteStop(
                            route_id=маршрут.id, customer_id=клиент.id,
                            sort_order=порядок * 10))

        session.commit()

        # --- несколько заказов для наглядности -----------------------------------
        _демо_заказы(session, случайно, товары, точки_по_филиалам, склады, агенты)
        session.commit()

    print("Демонстрационные данные загружены.\n")
    print("ВНИМАНИЕ: ассортимент, цены, магазины и ФИО вымышлены.")
    print("Перед боевым запуском заменить целиком.\n")
    print("Учётные записи (пароль показывается один раз):\n")
    print(f"  {'логин':<20} {'роль':<12} пароль")
    for логин, роль, пароль in пароли:
        print(f"  {логин:<20} {роль:<12} {пароль}")
    return 0


def _демо_заказы(session, случайно, товары, точки_по_филиалам, склады, агенты):
    """Заказы за прошедшую неделю в разных состояниях.

    Нужны, чтобы кабинет не открывался пустым: на пустых списках не видно
    ни расчёта долга, ни резервов, ни просрочки.
    """
    все_точки = [т for список in точки_по_филиалам.values() for т in список]
    сегодня = date.today()

    for сдвиг in range(7, 0, -1):
        день = сегодня - timedelta(days=сдвиг)
        for _ in range(случайно.randint(1, 3)):
            клиент = случайно.choice(все_точки)
            склад = склады["ЦС"]

            заказ = Order(
                client_uid=f"demo-{день.isoformat()}-{случайно.randint(100000, 999999)}",
                customer_id=клиент.id,
                agent_id=клиент.agent_id,
                warehouse_id=склад.id,
                price_type_id=клиент.price_type_id,
                date=день,
                payment_type=клиент.payment_type,
                source="mobile",
                comment="демонстрационный заказ",
            )

            for товар in случайно.sample(товары, случайно.randint(3, 8)):
                цена = services.price_for(session, товар.id, клиент.price_type_id)
                if цена <= 0:
                    continue
                кратность = int(товар.package_qty) or 1
                заказ.lines.append(OrderLine(
                    product_id=товар.id,
                    qty=Decimal(кратность * случайно.randint(1, 5)),
                    price=цена,
                    vat_rate=товар.vat_rate))

            if not заказ.lines:
                continue

            services.recalc_order(заказ)
            заказ.number = services.next_number(session, "order", "З")
            session.add(заказ)
            session.flush()

            # Старые заказы доводим до отгрузки, свежие оставляем в работе —
            # так в кабинете видно все состояния сразу.
            if сдвиг >= 5:
                services.confirm_order(session, заказ)
                отгрузка = services.ship_order(session, заказ, on=день)
                # Половину отгрузок оплачиваем: нужна и погашенная
                # задолженность, и висящая, и просроченная.
                if случайно.random() < 0.5:
                    session.add(_оплата(случайно, клиент, заказ, день))
            elif сдвиг >= 3:
                services.confirm_order(session, заказ)


def _оплата(случайно, клиент, заказ, день):
    from app.models import Payment
    import uuid as uuid_lib

    return Payment(
        client_uid=str(uuid_lib.uuid4()),
        number=f"П-демо-{случайно.randint(100000, 999999)}",
        customer_id=клиент.id,
        agent_id=клиент.agent_id,
        date=день + timedelta(days=1),
        amount=заказ.amount,
        kind="transfer" if клиент.deferral_days else "cash",
        collected=bool(клиент.deferral_days),
        comment="демонстрационная оплата",
    )


