"""Настройки. Всё чувствительное — из окружения, в код не попадает."""

import os

DATABASE_URL = os.getenv("DATABASE_URL", "postgresql+psycopg://smartsale@/smartsale")

# Подпись сессионных кук веб-кабинета и токенов устройств.
SECRET_KEY = os.getenv("SECRET_KEY", "")

# Сколько живёт сессия веб-кабинета без активности.
SESSION_HOURS = int(os.getenv("SESSION_HOURS", "12"))

# Сколько живёт токен мобильного устройства. Срок длинный намеренно: агент
# в поле не должен вводить пароль каждый день, а отзыв делается не сроком, а
# отключением устройства в бэкофисе — это мгновенно и адресно.
DEVICE_TOKEN_DAYS = int(os.getenv("DEVICE_TOKEN_DAYS", "90"))

# --- деньги ------------------------------------------------------------------
CURRENCY = os.getenv("CURRENCY", "UZS")

# Знаков после запятой в суммах. Для сума дробная часть на практике не нужна,
# но округление задаётся настройкой: та же система может считать в валюте с
# копейками, и менять из-за этого схему базы неправильно.
AMOUNT_SCALE = int(os.getenv("AMOUNT_SCALE", "2"))

# --- правила работы в поле ---------------------------------------------------
# Требовать координаты при отметке визита. По умолчанию выключено: в подвалах
# и на рынках GPS не ловит, и жёсткое требование просто останавливает работу.
REQUIRE_VISIT_GPS = os.getenv("REQUIRE_VISIT_GPS", "0") == "1"

# Сколько записей на сущность отдаётся за один запрос синхронизации.
SYNC_PAGE_SIZE = int(os.getenv("SYNC_PAGE_SIZE", "1000"))

# --- обмен с УТ (приём справочников) -----------------------------------------
# SmartSale ходит в HTTP-сервис расширения УТ и забирает справочники и акции.
# Каталог SmartSale — производный от УТ: uuid сущности = uid ссылки в 1С.
# Аутентификация двойная: Basic веб-сервера публикации (логин 1С в UTF-8) плюс
# наш токен заголовком X-SmartSale-Token.
UT_BASE_URL = os.getenv("UT_BASE_URL", "")
UT_LOGIN = os.getenv("UT_LOGIN", "")
UT_PASSWORD = os.getenv("UT_PASSWORD", "")
UT_TOKEN = os.getenv("UT_TOKEN", "")
# Таймаут одного запроса к УТ, секунд.
UT_TIMEOUT = int(os.getenv("UT_TIMEOUT", "60"))
